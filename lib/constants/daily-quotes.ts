// 날짜 문자열(YYYY-MM-DD) → 그날의 명언. epoch 일수 기준이라 매일 다음 문구로
// 넘어가고 365일 주기로 순환한다 (같은 날에는 항상 같은 문구 — 새로고침해도 유지).
export function dailyQuoteOf(dateStr: string) {
  const epochDay = Math.floor(Date.parse(`${dateStr}T00:00:00Z`) / 86_400_000);
  const index = ((epochDay % dailyQuotes.length) + dailyQuotes.length) % dailyQuotes.length;
  return dailyQuotes[index];
}
